    private void jButtonOdjavaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonOdjavaActionPerformed
        try {
            List<Umetnik> umetnici = komunikacija.Komunikacija.getInstance().ucitajUmetnika();
            Umetnik ulogovani = cordinator.Cordinator.getInstance().getUlogovani();
            
            int option = JOptionPane.showConfirmDialog(this, "Da li stvarno želite da se odjavite?", "POTVDRA", JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE);
            
            
            
            if (option == JOptionPane.YES_OPTION) {
                try{
                    
                    if(umetnici.contains(ulogovani)){
                        komunikacija.Komunikacija.getInstance().odjavaUlogovanog(ulogovani);
                        JOptionPane.showMessageDialog(this, "Sistem je odjavio umetnika.", "USPEH", JOptionPane.INFORMATION_MESSAGE);
                        for (Window window : Window.getWindows()) {
                            window.dispose();
                        }
                    }
                    else{
                        JOptionPane.showMessageDialog(this, "Sistem ne moze da odjavi umetnika/umetnik je obrisan.", "GREŠKA", JOptionPane.ERROR_MESSAGE);
                        for (Window window : Window.getWindows()) {
                            window.dispose();
                        }
                        Cordinator.getInstance().otvoriLoginFormu();
                    }
                    
                    
                    
                } catch(Exception exc){
                    JOptionPane.showMessageDialog(this, "Sistem ne moze da odjavi umetnika.", "GREŠKA", JOptionPane.ERROR_MESSAGE);
                    for (Window window : Window.getWindows()) {
                            window.dispose();
                        }
                    Cordinator.getInstance().otvoriLoginFormu();
                    //this.dispose();
                }
            }
        } catch (IOException ex) {
            JOptionPane.showMessageDialog(this, "Sistem ne moze da odjavi umetnika.", "GREŠKA", JOptionPane.ERROR_MESSAGE);
            for (Window window : Window.getWindows()) {
                            window.dispose();
                        }
            Cordinator.getInstance().otvoriLoginFormu();
            //this.dispose();
        } catch (ClassNotFoundException ex) {
            JOptionPane.showMessageDialog(this, "Sistem ne moze da odjavi umetnika.", "GREŠKA", JOptionPane.ERROR_MESSAGE);
            for (Window window : Window.getWindows()) {
                            window.dispose();
                        }
            Cordinator.getInstance().otvoriLoginFormu();
            //this.dispose();
        }
    }//GEN-LAST:event_jButtonOdjavaActionPerformed

