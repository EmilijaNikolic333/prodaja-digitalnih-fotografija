    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String port = jTextFieldPort.getText().trim();
        String url = jTextFieldURL.getText().trim();
        String korisnickoIme = jTextFieldkorisnickoIme.getText().trim();
        String sifra = String.valueOf(jPasswordFieldsifra.getPassword()).trim();

        // Validacija osnovnih podataka
        if (url.isEmpty() || !url.startsWith("jdbc:")) {
            JOptionPane.showMessageDialog(this, "Neispravan URL. Mora počinjati sa \"jdbc:\" i sadržati bazu.", "Greška", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (korisnickoIme.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Korisničko ime ne sme biti prazno.", "Greška", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            // Privremeno pokušaj konekciju sa datim parametrima
            java.sql.Connection testConn = java.sql.DriverManager.getConnection(url, korisnickoIme, sifra);
            testConn.close();

            // Ako je prošlo, čuvamo konfiguraciju
            konfiguracija.Konfiguracija.getInstance().setProperty("port", port);
            konfiguracija.Konfiguracija.getInstance().setProperty("url", url);
            konfiguracija.Konfiguracija.getInstance().setProperty("username", korisnickoIme);
            konfiguracija.Konfiguracija.getInstance().setProperty("password", sifra);
            konfiguracija.Konfiguracija.getInstance().sacuvajIzmene();

            JOptionPane.showMessageDialog(this, "Parametri su sačuvani i konekcija uspešna.", "USPEH", JOptionPane.INFORMATION_MESSAGE);
            this.dispose(); // zatvaranje forme samo ako je sve prošlo

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Konekcija sa bazom nije uspela. Proverite parametre.\n" + e.getMessage(),
                    "Greška pri konekciji", JOptionPane.ERROR_MESSAGE);
            // forma ostaje otvorena
        }
        
        
        
    }//GEN-LAST:event_jButton1ActionPerformed

