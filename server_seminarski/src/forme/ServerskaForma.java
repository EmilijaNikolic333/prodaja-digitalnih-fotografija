    private void jButtonPOKRENIActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonPOKRENIActionPerformed
        
       
        this.getjTableNeulogovani().setShowGrid(true); // Omogućava prikaz linija
        this.getjTableUlogovani().setShowGrid(true); // Omogućava prikaz linija

           
            controller.Controller.getInstance().setSf(this);
            
        
        
        
        
        ulogovani = new ArrayList<>();
        neulogovani = new ArrayList<>();
        
        try {
            if (serverThread == null || !serverThread.isAlive()) {
                server = new Server(); // napravi novu instancu Server-a
                serverThread = new Thread(server);
                serverThread.start();
                
                jLabelStatus.setText("POKRENUT");
                jButtonZAUSTAVI.setEnabled(true);
                jButtonPOKRENI.setEnabled(false);
            } else {
                jLabelStatus.setText("Server je već pokrenut.");
            }
            
            for (ObradaKlijentskihZahteva korisnik : server.getKlijenti()) {
                if(korisnik.getIme() != null && korisnik.getPrezime() != null && korisnik.getKorisnickoIme() != null && korisnik.getSifra() != null){
                    Umetnik u = new Umetnik(korisnik.getIme(), korisnik.getPrezime(), korisnik.getKorisnickoIme(), korisnik.getSifra());
                    
                    ulogovani.add(u);
                }
                
                
                
            }
            controller.Controller.getInstance().setUlogovaniUmetnici(ulogovani);
            umetnici = controller.Controller.getInstance().ucitajUmetnike();
            
            for (Umetnik u : umetnici) {
                if(!ulogovani.contains(u)){
                    neulogovani.add(u);
                }
            }
            
            ModelTabeleUmetnici mtu = new ModelTabeleUmetnici(ulogovani);
            jTableUlogovani.setModel(mtu);
            
            
            ModelTabeleUmetnici mtu1 = new ModelTabeleUmetnici(neulogovani);
            jTableNeulogovani.setModel(mtu1);
            
            centrirajTekst(jTableUlogovani);
            centrirajTekst(jTableNeulogovani);
            
            
        } catch (Exception ex) {
            Logger.getLogger(ServerskaForma.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jButtonPOKRENIActionPerformed

